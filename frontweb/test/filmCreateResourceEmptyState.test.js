import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { compileScript, parse } from '@vue/compiler-sfc'

const panel = readFileSync(new URL('../src/components/filmCreate/FilmCreateResourcePanel.vue', import.meta.url), 'utf8')

function emptyBlock(marker) {
  const start = panel.indexOf(marker)
  assert.ok(start >= 0, `缺少 ${marker}`)
  const relativeEnd = panel.slice(start).search(/<\/div>\r?\n\s*<\/div>/)
  assert.ok(relativeEnd > 0, `${marker} 空状态未闭合`)
  return panel.slice(start, start + relativeEnd)
}

test('角色空状态提供提取/添加，无剧集时指向创建或选择剧集', () => {
  const block = emptyBlock('v-if="characters.length === 0"')
  assert.match(block, /class="empty-tip resource-empty-tip"/)
  assert.match(block, /role="status"/)
  assert.match(block, /暂无角色，可用「剧本自动提取角色」或「添加角色」/)
  assert.match(block, /v-if="needsEpisode"/)
  assert.match(block, /v-if="!hasAnyEpisode"[\s\S]*goCreateEpisode/)
  assert.match(block, /v-else[\s\S]*goSelectEpisode/)
  assert.match(block, /aria-label="去创建剧集"/)
  assert.match(block, /aria-label="去选择剧集"/)
  assert.match(block, /:aria-label="extractCharactersEmptyAriaLabel"/)
  assert.match(block, /emit\('generate-characters'\)/)
  assert.match(block, /:aria-label="addCharacterEmptyAriaLabel"/)
  assert.match(block, /emit\('add-character'\)/)
  assert.match(block, /:reason="characterGenerationDisabledReason"/)
  assert.match(block, /:reason="projectActionDisabledReason"/)
})

