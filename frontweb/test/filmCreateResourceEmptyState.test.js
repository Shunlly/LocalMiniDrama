test('无剧集空状态走制作页 onAddEpisode / add-episode，不再点页头或静默滚走', () => {
  assert.match(panel, /const EPISODE_REQUIRED_REASON = '请先创建或选择剧集'/)
  assert.match(panel, /onAddEpisode: \{ type: Function/)
  assert.match(panel, /'add-episode'/)
  assert.match(panel, /function goCreateEpisode\(/)
  assert.match(panel, /props\.onAddEpisode\(\)/)
  assert.match(panel, /emit\('add-episode'\)/)
  const createFnStart = panel.indexOf('function goCreateEpisode')
  const createFnEnd = panel.indexOf('function goSelectEpisode')
  assert.ok(createFnStart >= 0 && createFnEnd > createFnStart)
  const createFn = panel.slice(createFnStart, createFnEnd)
  assert.match(createFn, /props\.onAddEpisode\(\)/)
  assert.match(createFn, /emit\('add-episode'\)/)
  assert.doesNotMatch(createFn, /activateExistingControl/)
  assert.doesNotMatch(createFn, /scrollToScriptAnchor/)
  assert.doesNotMatch(createFn, /header-add-episode/)
  assert.doesNotMatch(panel, /activateExistingControl\('\.header-add-episode'\)/)
  assert.doesNotMatch(panel, /activateExistingControl\('\[aria-label="添加一集"\]'\)/)
  assert.match(panel, /function goSelectEpisode\(/)
  assert.match(panel, /hasAnyEpisode: \{ type: Boolean/)
  assert.match(panel, /onSelectEpisode: \{ type: Function/)
  assert.match(panel, /'select-episode'/)
  const selectFnStart = panel.indexOf('function goSelectEpisode')
  const selectFnEnd = panel.indexOf('const resourceImageFileInput')
  assert.ok(selectFnStart >= 0 && selectFnEnd > selectFnStart)
  const selectFn = panel.slice(selectFnStart, selectFnEnd)
  assert.match(selectFn, /props\.onSelectEpisode\(\)/)
  assert.match(selectFn, /emit\('select-episode'\)/)
  assert.doesNotMatch(selectFn, /activateExistingControl/)
  assert.doesNotMatch(selectFn, /querySelector/)
  assert.doesNotMatch(selectFn, /getElementById/)
  assert.doesNotMatch(selectFn, /header-episode-select/)
  assert.doesNotMatch(panel, /activateExistingControl/)
  assert.doesNotMatch(panel, /header-episode-select/)
  assert.doesNotMatch(panel, /<div v-if="characters\.length === 0" class="empty-tip">暂无角色/)
})

test('资源面板含空状态后仍可编译', () => {
  const parsed = parse(panel, { filename: 'FilmCreateResourcePanel.vue' })
  assert.deepEqual(parsed.errors.map((error) => String(error)), [])
  assert.doesNotThrow(() => compileScript(parsed.descriptor, { id: 'resource-empty-state' }))
})
